package dev.adellaghmari.boundarymesh.domain.quarantine;

import dev.adellaghmari.boundarymesh.domain.ReasonCode;

public enum QuarantineReason {
    CONTRACT_DRIFT,
    CONTRACT_UNAVAILABLE,
    CONTRACT_VERSION_UNSUPPORTED,
    EGRESS_POLICY_UNAVAILABLE,
    CREDENTIAL_UNAVAILABLE,
    CREDENTIAL_REVOKED,
    CONSENT_INVALID,
    CONNECTOR_UNAVAILABLE,
    CONNECTOR_CIRCUIT_OPEN,
    DELIVERY_RETRIES_EXHAUSTED,
    PROVIDER_RATE_LIMITED,
    PROVIDER_TEMPORARY_FAILURE;

    public static QuarantineReason from(ReasonCode code) {
        if (code == null) {
            return CONNECTOR_UNAVAILABLE;
        }
        return switch (code.code()) {
            case "CONTRACT_DRIFT_DETECTED" -> CONTRACT_DRIFT;
            case "CONTRACT_UNAVAILABLE" -> CONTRACT_UNAVAILABLE;
            case "CONTRACT_UNSUPPORTED", "CONTRACT_VERSION_UNSUPPORTED" -> CONTRACT_VERSION_UNSUPPORTED;
            case "EGRESS_POLICY_UNAVAILABLE", "EGRESS_POLICY_INVALID" -> EGRESS_POLICY_UNAVAILABLE;
            case "CREDENTIAL_REVOKED" -> CREDENTIAL_REVOKED;
            case "CREDENTIAL_UNAVAILABLE", "CREDENTIAL_MISSING", "CREDENTIAL_PROVIDER_UNAVAILABLE" ->
                CREDENTIAL_UNAVAILABLE;
            case "CONSENT_MISSING", "CONSENT_REVOKED", "CONSENT_INVALID" -> CONSENT_INVALID;
            case "CONNECTOR_CIRCUIT_OPEN" -> CONNECTOR_CIRCUIT_OPEN;
            case "DELIVERY_RETRIES_EXHAUSTED" -> DELIVERY_RETRIES_EXHAUSTED;
            case "PROVIDER_RATE_LIMITED" -> PROVIDER_RATE_LIMITED;
            case "PROVIDER_TEMPORARY_FAILURE" -> PROVIDER_TEMPORARY_FAILURE;
            default -> CONNECTOR_UNAVAILABLE;
        };
    }
}
